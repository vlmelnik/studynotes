  info: invoke('app:info'),
  setSettings: invoke('app:setSettings'),
  chooseLibrary: invoke('app:chooseLibrary'),
  showLibraryFolder: invoke('app:showLibraryFolder'),
  closeReady: invoke('app:close-ready'),
  closeAck: invoke('app:close-ack'),
